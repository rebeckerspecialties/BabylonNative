//! Generates the WebXR WIT package from the W3C WebIDL vendored under Core/WebXr/idl.
//!
//! The WebXR modules extend each other through `partial interface` declarations (XRSession and
//! XRFrame are extended by eight modules), so the files are concatenated in dependency order and
//! converted as one definition set. A [`dom_profile::Profile`] removes what the deployment
//! targets cannot implement before conversion.

pub mod dom_profile;

use std::path::Path;

use anyhow::{bail, Context, Result};
use webidl2wit::{
    webidl_to_wit, ConversionOptions, HandleUnsupported, PackageName, ResourceInheritance,
};
use weedle::Parse;

/// Dependency order: the prelude shells, WebGPU types, the core device API, then the modules.
pub const IDL_ORDER: &[&str] = &[
    "dom-prelude.idl",
    "webgpu.idl",
    "webxr.idl",
    "webxr-ar-module.idl",
    "webxrlayers.idl",
    "webxr-webgpu-binding.idl",
    "webxr-depth-sensing.idl",
    "webxr-lighting-estimation.idl",
    "webxr-hit-test.idl",
    "anchors.idl",
    "raw-camera-access.idl",
    "webxr-hand-input.idl",
    "webxr-plane-detection.idl",
    "real-world-meshing.idl",
    "webxr-dom-overlays.idl",
    "webxr-gamepads-module.idl",
];

pub struct Generated {
    pub wit: String,
    pub profile_report: Option<dom_profile::Report>,
    pub placeholder_callbacks: Vec<String>,
}

fn parse_webidl(input: &str) -> Result<Vec<weedle::Definition<'_>>> {
    match weedle::Definitions::parse(input) {
        Ok(("", parsed)) => Ok(parsed),
        Ok((remaining, _))
        | Err(weedle::Err::Error((remaining, _)))
        | Err(weedle::Err::Failure((remaining, _))) => {
            let remaining: &str = remaining;
            let offset = input.len() - remaining.len();
            let line = input[..offset].matches('\n').count() + 1;
            let snippet: String = remaining.chars().take(120).collect();
            bail!("WebIDL parse stopped at byte {offset} (line {line}): {snippet:?}")
        }
        Err(e) => bail!("WebIDL parse failed: {e}"),
    }
}

/// Reads the IDL set from `idl_dir` in [`IDL_ORDER`] as one text.
pub fn read_idl_set(idl_dir: &Path) -> Result<String> {
    let mut input = String::new();
    for name in IDL_ORDER {
        let path = idl_dir.join(name);
        let text = std::fs::read_to_string(&path)
            .with_context(|| format!("reading {}", path.display()))?;
        input.push_str(&text);
        input.push('\n');
    }
    Ok(input)
}

/// Converts the IDL set to WIT text. The text is not validated here; see [`validate`].
pub fn generate(idl_dir: &Path, profile: Option<&dom_profile::Profile>) -> Result<Generated> {
    let version = std::fs::read_to_string(idl_dir.join("WEBREF_VERSION"))
        .context("reading WEBREF_VERSION")?
        .trim()
        .to_owned();
    let input = read_idl_set(idl_dir)?;
    let mut definitions = parse_webidl(&input)?;

    let profile_report = profile.map(|profile| dom_profile::apply(profile, &mut definitions));

    // webidl2wit 0.1.1 skips `callback` definitions but keeps the operations that take them, which
    // leaves dangling type names in the WIT. Callbacks become opaque resources here; frame pacing
    // (XRFrameRequestCallback) is modelled by the host's completion mechanism rather than a
    // callback in both bindings, so the resource is only a placeholder for the signature.
    let placeholder_callbacks: Vec<String> = definitions
        .iter()
        .filter_map(|definition| match definition {
            weedle::Definition::Callback(callback) => Some(callback.identifier.0.to_string()),
            _ => None,
        })
        .collect();
    definitions.retain(|definition| !matches!(definition, weedle::Definition::Callback(_)));

    let options = ConversionOptions {
        package_name: PackageName::new("webidl", "webxr", None),
        interface_name: "webxr".into(),
        unsupported_features: HandleUnsupported::Warn,
        resource_inheritance: ResourceInheritance::Both,
        phantom_interface: placeholder_callbacks.clone(),
        ..Default::default()
    };
    let package = webidl_to_wit(definitions, options).context("WebIDL to WIT conversion failed")?;

    let profile_note = if profile.is_some() {
        ", no-DOM profile"
    } else {
        ""
    };
    let wit = format!(
        "// Generated by Tools/webxr-idl-gen from Core/WebXr/idl ({version}{profile_note}). Do not edit; regenerate instead.\n{package}"
    );
    Ok(Generated {
        wit,
        profile_report,
        placeholder_callbacks,
    })
}

/// Resolves the WIT text against the packages vendored under `deps_dir` (wasi:io).
pub fn validate(wit: &str, deps_dir: &Path) -> Result<()> {
    let mut resolve = wit_parser::Resolve::default();
    for entry in
        std::fs::read_dir(deps_dir).with_context(|| format!("reading {}", deps_dir.display()))?
    {
        let entry = entry?;
        if entry.file_type()?.is_dir() {
            resolve
                .push_dir(entry.path())
                .with_context(|| format!("loading {}", entry.path().display()))?;
        }
    }
    resolve
        .push_str("webxr.wit", wit)
        .context("generated WIT does not resolve")?;
    Ok(())
}
